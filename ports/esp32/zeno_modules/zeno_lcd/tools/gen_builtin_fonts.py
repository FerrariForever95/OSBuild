#!/usr/bin/env python3
"""Regenerate zeno_font_data.c (the built-in fonts) from TrueType sources.

    python3 tools/gen_builtin_fonts.py            # uses the DejaVu fonts below
    python3 tools/gen_builtin_fonts.py --dejavu-dir /path/to/dejavu

Edit FONTS to change the built-in set. The ORDER defines the integer font ids
(lcd.FONT_* constants in modzlcd.c must match). DejaVu fonts are under the
permissive Bitstream Vera / DejaVu license.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ttf2zfont import build  # noqa: E402

# (c_name, ttf file, px size, bpp, first, last)
FONTS = [
    ("mono12",     "DejaVuSansMono.ttf",      12, 4, 32, 126),
    ("mono16",     "DejaVuSansMono.ttf",      16, 4, 32, 126),
    ("sans16",     "DejaVuSans.ttf",          16, 4, 32, 126),
    ("sansbold24", "DejaVuSans-Bold.ttf",     24, 4, 32, 126),
    ("digits48",   "DejaVuSans-Bold.ttf",     48, 4, 32, 58),   # ' '..':' : digits + - . , / % : etc.
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dejavu-dir", default="/usr/share/fonts/truetype/dejavu")
    ap.add_argument("-o", "--out", default=os.path.join(os.path.dirname(__file__), "..", "zeno_font_data.c"))
    a = ap.parse_args()

    out = ["/* GENERATED by tools/gen_builtin_fonts.py -- do not edit by hand.",
           " * Glyphs: DejaVu fonts (Bitstream Vera license, free to embed/redistribute). */",
           '#include "zeno_font.h"', ""]
    names = []
    for name, ttf, size, bpp, first, last in FONTS:
        data, h, asc = build(os.path.join(a.dejavu_dir, ttf), size, bpp, first, last)
        out.append(f"/* {name}: {ttf} {size}px {bpp}bpp U+{first:04X}..U+{last:04X}, "
                   f"line {h}px, {len(data)} bytes */")
        out.append(f"static const uint8_t font_{name}[{len(data)}] = {{")
        for i in range(0, len(data), 16):
            out.append("    " + ",".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
        out.append("};\n")
        names.append((name, len(data)))
    out.append("const zl_builtin_font_t zl_builtin_fonts[] = {")
    for name, n in names:
        out.append(f'    {{ "{name}", font_{name}, {n} }},')
    out.append("};")
    out.append(f"const int zl_builtin_font_count = {len(names)};")
    with open(a.out, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.abspath(a.out), "fonts:", ", ".join(f"{n}({s}B)" for n, s in names))


if __name__ == "__main__":
    main()
